pub fn raw_image_nt_headers64() -> Vec<u8> {
    let signature = [
        0xff, // Junk,
        0xff, 0x00, // Signature
        0x11, 0x22, 0x33,
    ];

    // File header (0x14 bytes) and optional header are zeroed. PeNet uses 0x70 bytes for the
    // optional header, which is enough for its lazy getters. The eager parser needs the complete
    // 32 bit optional header including all data directories (0xE0 bytes).
    let mut bytes = vec![0u8; 6 + 0x14 + 0xE0];
    bytes[..6].copy_from_slice(&signature);
    bytes
}
